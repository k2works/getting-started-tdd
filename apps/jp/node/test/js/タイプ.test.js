import { describe, expect, it } from "vitest";
import {
  タイプ番号,
  タイプ変換,
  タイプ生成,
  該当タイプなしエラー,
} from "../../src/js/タイプ.js";

describe("タイプ生成", () => {
  it("タイプ1は通常の変換をする", () => {
    const 通常 = タイプ生成(タイプ番号.通常);
    expect(タイプ変換(通常, 3)).toBe("Fizz");
    expect(通常.名前).toBe("通常");
  });

  it("タイプ2は数字だけを返す", () => {
    const 数字 = タイプ生成(タイプ番号.数字限定);
    expect(タイプ変換(数字, 3)).toBe("3");
    expect(数字.名前).toBe("数字限定");
  });

  it("タイプ3は15の倍数だけFizzBuzzを返す", () => {
    expect(タイプ変換(タイプ生成(3), 15)).toBe("FizzBuzz");
  });

  it("タイプ3は3の倍数を数字で返す", () => {
    expect(タイプ変換(タイプ生成(3), 3)).toBe("3");
  });

  it("存在しないタイプはエラーになる", () => {
    expect(() => タイプ生成(4)).toThrow(該当タイプなしエラー);
    expect(() => タイプ生成(4)).toThrow("該当するタイプは存在しません: 4");
  });
});
