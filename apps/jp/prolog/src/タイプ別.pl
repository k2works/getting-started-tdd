:- module(タイプ別, [タイプ生成/2, タイプ変換/3, タイプ名前/2]).

/** <module> 題材 B: タイプ別の変換（なでしこ3 の src/type.nako3 に対応）

  タイプは タイプ(名前, 変換) の項で表す。名前（通常・数字限定）は日本語のアトムで、
  引用符なしで書ける列挙子のように使える。
*/

:- use_module(基本変換).

%!  タイプ生成(+番号:integer, -タイプ) is det.
%
%   存在しない番号は タイプエラー(メッセージ) を投げる。
タイプ生成(1, タイプ(通常, 'FizzBuzz変換')) :- !.
タイプ生成(2, タイプ(数字限定, 数字限定変換)) :- !.
タイプ生成(3, タイプ('FizzBuzz限定', 'FizzBuzz限定変換')) :- !.
タイプ生成(_番号, _) :-
    format(string(_メッセージ), "該当するタイプは存在しません: ~w", [_番号]),
    throw(タイプエラー(_メッセージ)).

%!  タイプ名前(+タイプ, -名前:atom) is det.
タイプ名前(タイプ(_名前, _), _名前).

%!  タイプ変換(+タイプ, +数:integer, -結果:string) is det.
タイプ変換(タイプ(_, _変換), _数, _結果) :-
    call(_変換, _数, _結果).

数字限定変換(_数, _結果) :-
    number_string(_数, _結果).

'FizzBuzz限定変換'(_数, "FizzBuzz") :- 0 is _数 mod 15, !.
'FizzBuzz限定変換'(_数, _結果) :- number_string(_数, _結果).
