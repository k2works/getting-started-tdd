:- module(語順, [(は)/2, op(700, xfx, は), op(200, xfx, を), op(100, xfy, して)]).

/** <module> なでしこ3 の「3を FizzBuzz変換して装飾」という SOV 順を再現する演算子

  助詞「は」「を」「して」を演算子として定義し、次のように書けるようにする。

      _結果 は 3を 'FizzBuzz変換' して 装飾

  変数は大文字か _ で始める必要があるため、日本語の変数名には _ を付ける。
*/

:- meta_predicate は(?, :).

%!  は(-結果, +式) is det.
%
%   式「値 を 手順1 して 手順2 ...」を左から順に適用した結果を返す。
_結果 は _モジュール:(_値 を _手順) :-
    適用(_手順, _モジュール, _値, _結果).

適用(_前 して _後, _モジュール, _値, _結果) :-
    !,
    適用(_前, _モジュール, _値, _途中),
    適用(_後, _モジュール, _途中, _結果).
適用(_手順, _モジュール, _値, _結果) :-
    call(_モジュール:_手順, _値, _結果).
