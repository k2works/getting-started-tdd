:- module(エラー処理, [安全変換/2]).

/** <module> 題材 D: 安全変換（なでしこ3 の src/error.nako3 に対応）

  変換結果は 成功(値) か 失敗(メッセージ) の項で表す。
*/

:- use_module(基本変換).

%!  安全変換(+値, -変換結果) is det.
安全変換(_値, 失敗(_メッセージ)) :-
    \+ number(_値),
    !,
    format(string(_メッセージ), "数値を指定してください: ~w", [_値]).
安全変換(_値, 失敗(_メッセージ)) :-
    _値 =< 0,
    !,
    format(string(_メッセージ), "正の数を指定してください: ~w", [_値]).
安全変換(_値, 成功(_結果)) :-
    'FizzBuzz変換'(_値, _結果).
