"""ボウリングの得点計算（入力の投球列から出力の得点への関数として書く）"""


def 得点計算処理(投球列: list[int]) -> int:
    得点 = 0
    位置 = 0
    for _ in range(10):
        if 投球列[位置] == 10:
            得点 = 得点 + 10 + 投球列[位置 + 1] + 投球列[位置 + 2]
            位置 = 位置 + 1
        elif 投球列[位置] + 投球列[位置 + 1] == 10:
            得点 = 得点 + 10 + 投球列[位置 + 2]
            位置 = 位置 + 2
        else:
            得点 = 得点 + 投球列[位置] + 投球列[位置 + 1]
            位置 = 位置 + 2
    return 得点


def 同値連結処理(配列: list[int], PINS: int, N: int) -> list[int]:
    結果 = list(配列)
    for 番号 in range(1, N + 1):
        結果.append(PINS)
    return 結果
