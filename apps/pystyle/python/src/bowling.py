"""ボウリングの得点計算（入力の投球列から出力の得点への関数として書く）"""

from typing import Final

フレーム総数: Final = 10
全ピン数: Final = 10


def 得点計算処理(投球列: list[int]) -> int:
    得点 = 0
    位置 = 0
    for _ in range(フレーム総数):
        if ストライク判定処理(投球列, 位置):
            得点 = 得点 + フレーム得点処理(投球列, 位置, 投球数=1, ボーナス数=2)
            位置 = 位置 + 1
        elif スペア判定処理(投球列, 位置):
            得点 = 得点 + フレーム得点処理(投球列, 位置, 投球数=2, ボーナス数=1)
            位置 = 位置 + 2
        else:
            得点 = 得点 + フレーム得点処理(投球列, 位置, 投球数=2, ボーナス数=0)
            位置 = 位置 + 2
    return 得点


def ストライク判定処理(投球列: list[int], 位置: int) -> bool:
    return 投球列[位置] == 全ピン数


def スペア判定処理(投球列: list[int], 位置: int) -> bool:
    return 投球列[位置] + 投球列[位置 + 1] == 全ピン数


def フレーム得点処理(投球列: list[int], 位置: int, 投球数: int, ボーナス数: int) -> int:
    """そのフレームで使う投球数と、ボーナスとして加算する投球数の合計を足す"""
    return sum(投球列[位置 : 位置 + 投球数 + ボーナス数])


def 同値連結処理(配列: list[int], PINS: int, N: int) -> list[int]:
    結果 = list(配列)
    for 番号 in range(1, N + 1):
        結果.append(PINS)
    return 結果
