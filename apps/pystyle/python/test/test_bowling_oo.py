"""ボウリングのテスト（オブジェクト指向版。なでしこ3 版の test/bowling_oo_test.nako3 と同じ検証を並べる）"""

from src.bowling_oo import ゲーム


def test_オブジェクト指向版もスペアを加算する() -> None:
    対象ゲーム = ゲーム()
    対象ゲーム.投球処理(5)
    対象ゲーム.投球処理(5)
    対象ゲーム.投球処理(3)
    対象ゲーム.連続投球処理(0, 17)
    assert 対象ゲーム.得点取得処理() == 16


def test_2つ目のゲームは状態を共有しない() -> None:
    ゲーム1 = ゲーム()
    ゲーム1.連続投球処理(0, 20)
    ゲーム2 = ゲーム()
    ゲーム2.連続投球処理(10, 12)
    assert ゲーム2.得点取得処理() == 300
    assert len(ゲーム1.投球列) == 20
